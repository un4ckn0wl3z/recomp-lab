#!/usr/bin/env python3
"""
recomp.py — static recompiler: ROM ของ R16  ->  ซอร์ส C
=============================================================
หลักการ (แบบเดียวกับ N64Recomp / XenonRecomp แต่ย่อส่วน):
  * ฟังก์ชันของเกม 1 ตัว  -> ฟังก์ชัน C 1 ตัว   (func_XXXX)
  * branch target          -> label ของ C      (L_XXXX:)
  * jmp/jz/jnz             -> goto / if (...) goto
  * call / ret             -> เรียกฟังก์ชัน C / return
  * jr (indirect jump)     -> switch เฉพาะปลายทางที่รู้จัก, ที่เหลือ -> rt_bad_jump()
  * sys                    -> เรียก runtime (เทียบได้กับ HLE ของ hardware)
  * สถานะ CPU (รีจิสเตอร์+หน่วยความจำ) อยู่ใน struct Ctx ที่ส่งไปทุกฟังก์ชัน

สิ่งที่ "ไม่" ทำ = สมมุติฐานของ static recomp ทั่วไป:
  * ไม่รองรับ self-modifying code (โค้ดถูกแปลครั้งเดียวตอน build)
  * ไม่รองรับ jump ไปยัง address ที่ไม่ถูกค้นพบตอนวิเคราะห์

ใช้งาน:
  python3 tools/recomp.py given/game.rom -o out [--hints FILE] [--auto-tables]
"""
import os
import sys
import argparse

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'isa'))
sys.path.insert(0, os.path.dirname(__file__))
from r16 import MEM_SIZE, NO_FALLTHROUGH, fmt_insn  # noqa: E402
from analysis import analyze, load_hints, branch_targets  # noqa: E402


def R(n):
    return f'c->r[{n}]'


def translate(i):
    """แปลคำสั่ง R16 หนึ่งคำสั่ง -> statement ภาษา C"""
    n, x, y, z, imm = i.name, i.x, i.y, i.z, i.imm
    binop = {'add': '+', 'sub': '-', 'and': '&', 'or': '|', 'xor': '^'}
    if n == 'halt':
        return 'rt_halt(c); return;'
    if n == 'ldi':
        return f'{R(x)} = 0x{imm:04X};'
    if n == 'mov':
        return f'{R(x)} = {R(y)};'
    if n in binop:
        return f'{R(x)} = (uint16_t)({R(y)} {binop[n]} {R(z)});'
    if n in ('shl', 'shr'):
        # ระวัง: ใน C การ shift >= ความกว้างของ int เป็น undefined behavior
        # ต้องเลียนแบบพฤติกรรมของ CPU จริงให้เป๊ะ (ที่นี่: ได้ 0)
        if z >= 16:
            return f'{R(x)} = 0;'
        op = '<<' if n == 'shl' else '>>'
        return f'{R(x)} = (uint16_t)({R(y)} {op} {z});'
    if n == 'addi':
        return f'{R(x)} = (uint16_t)({R(x)} + 0x{imm:04X});'
    if n == 'ldb':
        return f'{R(x)} = MEM8({R(y)} + {z});'
    if n == 'stb':
        return f'MEM8({R(y)} + {z}) = (uint8_t){R(x)};'
    if n == 'jmp':
        return f'goto L_{imm:04X};'
    if n == 'jz':
        return f'if ({R(x)} == 0) goto L_{imm:04X};'
    if n == 'jnz':
        return f'if ({R(x)} != 0) goto L_{imm:04X};'
    if n == 'call':
        return f'func_{imm:04X}(c);'
    if n == 'ret':
        return 'return;'
    if n == 'sys':
        return f'rt_sys(c, {x});'
    if n == 'eq':
        return f'{R(x)} = ({R(y)} == {R(z)});'
    if n == 'lt':
        return f'{R(x)} = ({R(y)} < {R(z)});'
    raise ValueError(n)


def emit_func(f, out):
    targets = branch_targets(f)
    addrs = sorted(f.insns)
    # คำสั่งที่ไหลต่อ แต่คำสั่งถัดไปในลิสต์ไม่ได้อยู่ติดกัน -> ต้องใส่ goto เอง
    for k, a in enumerate(addrs):
        i = f.insns[a]
        nxt = addrs[k + 1] if k + 1 < len(addrs) else None
        if i.name not in NO_FALLTHROUGH and nxt != a + 4:
            targets.add(a + 4)

    out.append(f'void func_{f.entry:04X}(Ctx *c) {{')
    for k, a in enumerate(addrs):
        i = f.insns[a]
        if a in targets:
            out.append(f'L_{a:04X}:')
        asm = fmt_insn(i)
        if i.name == 'jr':
            out.append(f'    /* {a:04X}: {asm:<22} */ switch ({R(i.x)}) {{')
            for t in sorted(set(f.jr_targets.get(a, []))):
                out.append(f'        case 0x{t:04X}: goto L_{t:04X};')
            out.append(f'        default: rt_bad_jump(c, {R(i.x)}, 0x{a:04X}); return;')
            out.append('    }')
        else:
            out.append(f'    /* {a:04X}: {asm:<22} */ {translate(i)}')
        nxt = addrs[k + 1] if k + 1 < len(addrs) else None
        if i.name not in NO_FALLTHROUGH and nxt != a + 4:
            out.append(f'    goto L_{a + 4:04X};')
    out.append('}')
    out.append('')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rom')
    ap.add_argument('-o', '--outdir', required=True)
    ap.add_argument('--hints')
    ap.add_argument('--auto-tables', action='store_true')
    a = ap.parse_args()

    rom = open(a.rom, 'rb').read()
    mem = bytearray(MEM_SIZE)
    mem[:len(rom)] = rom
    funcs, hints = analyze(mem, len(rom), 0, load_hints(a.hints), a.auto_tables,
                           lambda s: print('[recomp]' + s))

    os.makedirs(a.outdir, exist_ok=True)
    out = ['/* AUTO-GENERATED by tools/recomp.py — static recompilation of game.rom */',
           '#include "runtime.h"', '']
    for e in sorted(funcs):
        out.append(f'void func_{e:04X}(Ctx *c);')
    out.append('')
    for e in sorted(funcs):
        emit_func(funcs[e], out)
    out.append('void recomp_entry(Ctx *c) { func_0000(c); }')
    open(os.path.join(a.outdir, 'recomp_game.c'), 'w').write('\n'.join(out) + '\n')

    # ROM ทั้งก้อนยังต้องฝังไว้ เพราะเกมอ่าน "ข้อมูล" (string, แผนที่, table) จาก ROM
    rows = [', '.join(f'0x{b:02X}' for b in rom[k:k + 16]) for k in range(0, len(rom), 16)]
    open(os.path.join(a.outdir, 'rom_image.c'), 'w').write(
        '/* AUTO-GENERATED: ROM data image */\n#include <stdint.h>\n'
        f'const uint32_t rom_size = {len(rom)};\n'
        'const uint8_t rom_image[] = {\n    ' + ',\n    '.join(rows) + '\n};\n')

    n_insn = sum(len(f.insns) for f in funcs.values())
    unresolved = [j for f in funcs.values() for j in f.unresolved_jr]
    print(f'[recomp] {len(funcs)} functions, {n_insn} instructions -> {a.outdir}/recomp_game.c')
    for j in unresolved:
        print(f'[recomp] WARNING: unresolved JR at 0x{j:04X} — โค้ดปลายทางจะไม่ถูกแปล!')


if __name__ == '__main__':
    main()
